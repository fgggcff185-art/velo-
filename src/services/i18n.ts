export function t(key: string): string {
  const lang = (useSettingsStore.getState().settings as unknown as { language?: Lang }).language || 'ar';
  return dict[lang]?.[key] || dict.en[key] || key;
}

export function useT() {
  const lang = (useSettingsStore((s) => (s.settings as unknown as { language?: Lang }).language)) || 'ar';
  return (key: string) => dict[lang]?.[key] || dict.en[key] || key;
}

export function getDir(lang?: string): 'rtl' | 'ltr' {
  return lang === 'ar' ? 'rtl' : 'ltr';
}
